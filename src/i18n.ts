export const UI_TRANSLATED_LANGUAGES = ["en-US", "uk-UA", "es-ES", "fr-FR", "de-DE", "pl-PL", "it-IT"] as const;

export function detectBrowserLanguage(): AppLanguage {
  if (typeof navigator === "undefined") return "en-US";
  const translated = new Set<string>(UI_TRANSLATED_LANGUAGES);
  for (const candidate of navigator.languages.length ? navigator.languages : [navigator.language]) {
    try {
      const locale = Intl.getCanonicalLocales(candidate)[0];
      const exactMatch = SUPPORTED_LANGUAGES.find(({ code }) => code.toLowerCase() === locale.toLowerCase());
      if (exactMatch && translated.has(exactMatch.code)) return exactMatch.code;
      const baseLanguage = locale.split("-")[0].toLowerCase();
      const translatedMatch = SUPPORTED_LANGUAGES.find(
        ({ code }) => code.split("-")[0].toLowerCase() === baseLanguage && translated.has(code),
      );
      if (translatedMatch) return translatedMatch.code;
    } catch {
      continue;
    }
  }
  return "en-US";
}

